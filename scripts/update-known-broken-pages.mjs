// Rebuilds tests/uat/signed-in/data/known-broken-pages.json from the last uat-all-pages run.
// Each failed page is filed by the check that failed: 404 page, empty page, or 5xx API error.
// Pages that now work ("expected to fail, but passed") are dropped from the list.
// Usage: npm run test:uat:all-pages ; node scripts/update-known-broken-pages.mjs
import fs from 'fs';
import path from 'path';

const OUT = 'tests/uat/signed-in/data/known-broken-pages.json';
const RESULTS = 'test-results';
const catalog = JSON.parse(fs.readFileSync('tests/uat/signed-in/data/route-catalog.json', 'utf8'));
const current = fs.existsSync(OUT) ? JSON.parse(fs.readFileSync(OUT, 'utf8')) : {};
const kinds = { notFound: 'menu link opens the 404 page', empty: 'page is empty', serverError: 'API calls returned 5xx' };

const found = { notFound: new Set(), empty: new Set(), serverError: new Set() };
const fixed = new Set();
const unclassified = [];
for (const dir of fs.existsSync(RESULTS) ? fs.readdirSync(RESULTS) : []) {
  if (!dir.includes('all-pages')) continue;
  const ctx = path.join(RESULTS, dir, 'error-context.md');
  if (!fs.existsSync(ctx)) continue;
  const full = fs.readFileSync(ctx, 'utf8');
  // Only the error section: the file also contains the test source, which mentions every marker.
  const text = full.split('# Page snapshot')[0].split('# Test source')[0];
  const name = text.split('\n').find(l => l.startsWith('- Name:')) || '';
  const p = /\((\/[^)\s]+)\)\s*$/.exec(name)?.[1];
  if (!p) continue;
  if (text.includes('Expected to fail, but passed')) { fixed.add(p); continue; }
  const kind = Object.keys(kinds).find(k => text.includes(kinds[k]));
  if (kind) found[kind].add(p); else unclassified.push(`${p}: ${(/Error: .*/.exec(text) || ['?'])[0].slice(0, 120)}`);
}

const order = new Map(catalog.routes.map((r, i) => [r.path, i]));
const sorted = s => [...s].sort((a, b) => (order.get(a) ?? 1e9) - (order.get(b) ?? 1e9));
const out = { found: current.found || new Date().toISOString().slice(0, 10), updated: new Date().toISOString().slice(0, 10),
  note: 'Pages that are broken on UAT, by kind. Generated by scripts/update-known-broken-pages.mjs from the last uat-all-pages run.' };
for (const kind of Object.keys(kinds)) {
  // Keep earlier entries that did not run this time or still fail; drop ones that now pass.
  const kept = (current[kind] || []).filter(p => !fixed.has(p));
  out[kind] = sorted(new Set([...kept, ...found[kind]]));
}
fs.writeFileSync(OUT, JSON.stringify(out, null, 1) + '\n');
if (unclassified.length) console.log(['Not filed (other failures, check these):', ...unclassified].join('\n  '));
console.log(`known-broken-pages.json: ${out.notFound.length} not found, ${out.empty.length} empty, ${out.serverError.length} server error; ${fixed.size} now fixed`);
