// Writes docs/UAT-TEST-CASES.md: every UAT test file, its purpose line and its test cases.
// Usage: node scripts/list-uat-testcases.mjs   (reads the test list; sends no traffic to the site)
import { execSync } from 'child_process';
import fs from 'fs';
import path from 'path';

const json = JSON.parse(execSync('npx playwright test -c playwright.uat.config.ts --list --reporter=json', { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 }));

const files = new Map();
const walk = (suite, file) => {
  for (const s of suite.suites || []) walk(s, s.file || file);
  for (const spec of suite.specs || []) {
    const f = spec.file || file;
    if (!files.has(f)) files.set(f, { titles: new Map() });
    const entry = files.get(f).titles;
    const projects = spec.tests.map(t => t.projectName);
    const prev = entry.get(spec.title) || new Set();
    projects.forEach(p => prev.add(p));
    entry.set(spec.title, prev);
  }
};
for (const s of json.suites) walk(s, s.file);

const purposeOf = file => {
  const src = fs.readFileSync(path.join('tests/uat', file), 'utf8');
  return (/\/\/ Purpose: (.+)/.exec(src)?.[1] || '').trim();
};
const shortProjects = set => [...set].map(p => p.replace('uat-', '')).join(', ');

let md = '# UAT test cases\n\n';
md += 'Functional tests for https://uat.leecycle.dev. Generated by `node scripts/list-uat-testcases.mjs`; do not edit by hand.\n\n';
md += 'Tests marked **known issue** document a defect found on UAT. They pass while the defect exists and report "expected to fail, but passed" once it is fixed; then remove their `test.fail()` line.\n\n';
const order = [...files.keys()].sort((a, b) => a.localeCompare(b));
let total = 0;
md += '| File | Purpose | Cases |\n|---|---|---:|\n';
for (const f of order) md += `| \`tests/uat/${f.replace(/\\/g, '/')}\` | ${purposeOf(f)} | ${files.get(f).titles.size} |\n`;
for (const f of order) {
  const { titles } = files.get(f);
  total += titles.size;
  md += `\n## ${f.replace(/\\/g, '/')}\n\n${purposeOf(f)}\n\n| Test case | Runs on |\n|---|---|\n`;
  const rows = [...titles];
  // The all-pages file has one case per menu page: summarise instead of listing ~500 rows.
  if (rows.length > 60) {
    md += `| ${rows.length} generated cases, one per page in \`signed-in/data/route-catalog.json\` (e.g. "${rows[0][0]}") | ${shortProjects(rows[0][1])} |\n`;
    continue;
  }
  for (const [t, p] of rows) md += `| ${t.replace(/\|/g, '\\|')} | ${shortProjects(p)} |\n`;
}
md += `\n**Total: ${total} test cases in ${order.length} files.**\n`;
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/UAT-TEST-CASES.md', md);
console.log(`Wrote docs/UAT-TEST-CASES.md: ${total} cases in ${order.length} files`);
